package main

import (
	"bytes"
	"fmt"
)

// netSpec describes one sorting network instantiation.
type netSpec struct {
	rows  int    // vectors held live, and the number of keys per lane
	lanes int    // lanes per vector
	width int    // key width in bits
	elem  string // Go element type
	vec   string // archsimd vector type
}

// emitNetwork writes a straight-line bitonic sort over rows vectors, sorting
// rows*lanes keys entirely in registers.
//
// The layout is what makes this affordable. The logical index of the key in row
// r, lane j is j*rows + r, so every logical distance below rows is a distance
// between whole vectors - a plain Min and Max on a register pair - and only the
// distances at or above rows need a lane shuffle. With 16 rows that leaves the
// expensive lane work in 3 of the 21 substages instead of 11. The cost is one
// transpose at the end, to turn the column-major result back into the
// contiguous order the caller expects.
//
// Since the input is unsorted, the assignment of keys to (row, lane) positions
// is free: the loader reads contiguously and simply declares the layout.
func emitNetwork(s netSpec) []byte {
	n := s.rows * s.lanes
	var b bytes.Buffer
	p := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }

	p("//go:build goexperiment.simd && arm64")
	p("")
	p("package vqsort")
	p("")
	p(`import "simd/archsimd"`)
	p("")
	p("// sortNetworkI%d sorts the %d keys in buf with a data-oblivious bitonic", s.width, n)
	p("// network: no branches, and %d vector registers live throughout, so no", s.rows)
	p("// memory traffic between stages.")
	p("//")
	p("// Generated by gen; DO NOT EDIT.")
	p("func sortNetworkI%d(buf *[%d]%s) {", s.width, n, s.elem)

	for r := 0; r < s.rows; r++ {
		p("\tv%d := archsimd.Load%sArray((*[%d]%s)(buf[%d:%d]))", r, s.vec, s.lanes, s.elem, r*s.lanes, (r+1)*s.lanes)
	}
	p("\tvar mn, mx, sh archsimd.%s", s.vec)
	p("\t_, _, _ = mn, mx, sh")

	// A compare-exchange's direction follows the low element's logical index.
	// For small k that is decided by the row, so a whole vector pair shares it;
	// for k at or above rows it is decided by the lane, and the two results have
	// to be blended per lane.
	for k := 2; k <= n; k *= 2 {
		for j := k / 2; j >= 1; j /= 2 {
			if j < s.rows {
				emitRowStage(p, s, k, j)
			} else {
				emitLaneStage(p, s, k, j)
			}
		}
	}

	emitTranspose(p, s)
	p("}")
	return b.Bytes()
}

func emitRowStage(p func(string, ...any), s netSpec, k, j int) {
	perLane := k >= s.rows && k < s.rows*s.lanes
	for r := 0; r < s.rows; r++ {
		if r&j != 0 {
			continue
		}
		a, c := r, r|j
		switch {
		case perLane:
			p("\tmn, mx = minKeyI%d(v%d, v%d), maxKeyI%d(v%d, v%d)", s.width, a, c, s.width, a, c)
			p("\tv%d, v%d = mn.IfElse(dirMask%dK%d(), mx), mx.IfElse(dirMask%dK%d(), mn)", a, c, s.width, k, s.width, k)
		case r&k == 0:
			p("\tv%d, v%d = minKeyI%d(v%d, v%d), maxKeyI%d(v%d, v%d)", a, c, s.width, a, c, s.width, a, c)
		default:
			p("\tv%d, v%d = maxKeyI%d(v%d, v%d), minKeyI%d(v%d, v%d)", a, c, s.width, a, c, s.width, a, c)
		}
	}
}

func emitLaneStage(p func(string, ...any), s netSpec, k, j int) {
	dl := j / s.rows
	for r := 0; r < s.rows; r++ {
		p("\tsh = v%d.ToBits().ReshapeToUint8s().LookupOrZero(laneSwap%dD%d()).ReshapeToUint%ds().BitsToInt%d()",
			r, s.width, dl, s.width, s.width)
		p("\tmn, mx = minKeyI%d(v%d, sh), maxKeyI%d(v%d, sh)", s.width, r, s.width, r)
		p("\tv%d = mn.IfElse(keepMin%dK%dD%d(), mx)", r, s.width, k, dl)
	}
}

// emitTranspose turns the column-major result back into contiguous order. The
// key with logical index L sits in row L%rows, lane L/rows, so each group of
// `lanes` consecutive rows transposes into `lanes` output vectors, which land
// `rows` keys apart in the buffer.
//
// The interleaves run on the bit view rather than on the key type, because
// arm64 exposes ZIP1 and ZIP2 only for integer vectors. Reinterpreting is free
// and keeps this identical for integer and floating-point keys.
func emitTranspose(p func(string, ...any), s netSpec) {
	store := func(src string, off int) {
		p("\t%s.ReshapeToUint%ds().BitsToInt%d().StoreArray((*[%d]%s)(buf[%d:%d]))",
			src, s.width, s.width, s.lanes, s.elem, off, off+s.lanes)
	}

	if s.lanes == 2 {
		// A 2x2 transpose is just the two 64-bit interleaves, and the result is
		// already at the key width, so no reshape is needed.
		p("\tvar z0, z1 archsimd.Uint64x2")
		p("\t_, _ = z0, z1")
		for m := 0; m < s.rows/2; m++ {
			a, c := 2*m, 2*m+1
			p("\tz0 = v%d.ToBits().InterleaveLo(v%d.ToBits())", a, c)
			p("\tz1 = v%d.ToBits().InterleaveHi(v%d.ToBits())", a, c)
			p("\tz0.BitsToInt64().StoreArray((*[2]%s)(buf[%d:%d]))", s.elem, 2*m, 2*m+2)
			p("\tz1.BitsToInt64().StoreArray((*[2]%s)(buf[%d:%d]))", s.elem, s.rows+2*m, s.rows+2*m+2)
		}
		return
	}

	p("\tvar t0, t1, t2, t3 archsimd.Uint32x4")
	p("\tvar u0, u1, u2, u3 archsimd.Uint64x2")
	p("\t_, _, _, _ = t0, t1, t2, t3")
	p("\t_, _, _, _ = u0, u1, u2, u3")
	for m := 0; m < s.rows/s.lanes; m++ {
		a, c, d, e := s.lanes*m, s.lanes*m+1, s.lanes*m+2, s.lanes*m+3
		p("\tt0 = v%d.ToBits().InterleaveLo(v%d.ToBits())", a, c)
		p("\tt1 = v%d.ToBits().InterleaveHi(v%d.ToBits())", a, c)
		p("\tt2 = v%d.ToBits().InterleaveLo(v%d.ToBits())", d, e)
		p("\tt3 = v%d.ToBits().InterleaveHi(v%d.ToBits())", d, e)
		for i, t := range []string{"t0", "t1", "t2", "t3"} {
			p("\tu%d = %s.ReshapeToUint64s()", i, t)
		}
		pairs := []struct{ x, y, op string }{
			{"u0", "u2", "InterleaveLo"},
			{"u0", "u2", "InterleaveHi"},
			{"u1", "u3", "InterleaveLo"},
			{"u1", "u3", "InterleaveHi"},
		}
		for j, q := range pairs {
			store(fmt.Sprintf("%s.%s(%s)", q.x, q.op, q.y), j*s.rows+s.lanes*m)
		}
	}
}
