// Command gen derives the floating-point kernels from the integer ones.
//
// The 4-lane kernel and the 2-lane kernel are written by hand, in
// kernel_i32_neon.go and kernel_i64_neon.go. Their float counterparts differ
// only in element and vector type names: every operation the partition uses -
// Less, the loads and stores, the broadcast, the byte-wise table lookup - has
// the same name on Float32x4 and Float64x2 as on the integer vectors. Go
// generics cannot abstract over the archsimd vector types, since the methods
// return concrete types and there is no interface to constrain, so the choice is
// between copies that drift apart and a rewrite that cannot.
//
// What is not derived: the float entry points, which have to move NaNs aside
// before anything compares keys. Those are hand-written in float_neon.go.
//
// Usage: go generate ./...
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"strings"
)

type rewrite struct {
	from, to string
	// entry is the kernel entry point to drop; the float kernels get a
	// hand-written one that runs the NaN prepass first.
	entry string
	subs  []sub
}

type sub struct {
	pattern *regexp.Regexp
	repl    string
}

func lit(from, to string) sub { return sub{regexp.MustCompile(regexp.QuoteMeta(from)), to} }
func re(pattern, repl string) sub {
	return sub{regexp.MustCompile(pattern), repl}
}

func main() {
	rewrites := []rewrite{
		{
			from:  "kernel_i32_neon.go",
			to:    "kernel_f32_neon.go",
			entry: "sortInt32NEON",
			subs: []sub{
				lit("LoadInt32x4Array", "LoadFloat32x4Array"),
				lit("BroadcastInt32x4", "BroadcastFloat32x4"),
				lit("BitsToInt32", "BitsToFloat32"),
				lit("archsimd.Int32x4", "archsimd.Float32x4"),
				re(`\bint32\b`, "float32"),
				re(`\b(\w+)I32\b`, "${1}F32"),
			},
		},
		{
			from: "network_i32_neon.go",
			to:   "network_f32_neon.go",
			subs: []sub{
				lit("LoadInt32x4Array", "LoadFloat32x4Array"),
				lit("BitsToInt32", "BitsToFloat32"),
				lit("archsimd.Int32x4", "archsimd.Float32x4"),
				re(`\bint32\b`, "float32"),
				re(`\b(\w+)I32\b`, "${1}F32"),
			},
		},
		{
			from: "network_i64_neon.go",
			to:   "network_f64_neon.go",
			subs: []sub{
				lit("LoadInt64x2Array", "LoadFloat64x2Array"),
				lit("BitsToInt64", "BitsToFloat64"),
				lit("archsimd.Int64x2", "archsimd.Float64x2"),
				re(`\bint64\b`, "float64"),
				re(`\b(\w+)I64\b`, "${1}F64"),
			},
		},
		{
			from:  "kernel_i64_neon.go",
			to:    "kernel_f64_neon.go",
			entry: "sortInt64NEON",
			subs: []sub{
				lit("LoadInt64x2Array", "LoadFloat64x2Array"),
				lit("BroadcastInt64x2", "BroadcastFloat64x2"),
				lit("BitsToInt64", "BitsToFloat64"),
				lit("archsimd.Int64x2", "archsimd.Float64x2"),
				re(`\bint64\b`, "float64"),
				re(`\b(\w+)I64\b`, "${1}F64"),
			},
		},
	}

	// The 4-lane sorting network is emitted rather than rewritten; the float
	// version is then derived from it like the kernels.
	for _, spec := range []netSpec{
		{rows: 16, lanes: 4, width: 32, elem: "int32", vec: "Int32x4"},
		{rows: 16, lanes: 2, width: 64, elem: "int64", vec: "Int64x2"},
	} {
		out := fmt.Sprintf("network_i%d_neon.go", spec.width)
		if err := writeFormatted(out, emitNetwork(spec)); err != nil {
			fmt.Fprintf(os.Stderr, "gen: %v\n", err)
			os.Exit(1)
		}
	}

	for _, r := range rewrites {
		if err := derive(r); err != nil {
			fmt.Fprintf(os.Stderr, "gen: %v\n", err)
			os.Exit(1)
		}
	}
}

func derive(r rewrite) error {
	src, err := os.ReadFile(r.from)
	if err != nil {
		return err
	}
	s := string(src)

	// The width constants and the byte tables are shared with the integer
	// kernel; keep one definition.
	s = regexp.MustCompile(`(?s)\nconst \(.*?\n\)\n`).ReplaceAllString(s, "\n")

	// Drop the integer kernel's entry point and its doc comment.
	if r.entry != "" {
		entry := regexp.MustCompile(`(?ms)^(//[^\n]*\n)*func ` + r.entry + `\(.*?^\}\n`)
		if !entry.MatchString(s) {
			return fmt.Errorf("%s: entry point %s not found", r.from, r.entry)
		}
		s = entry.ReplaceAllString(s, "")
	}

	for _, sb := range r.subs {
		s = sb.pattern.ReplaceAllString(s, sb.repl)
	}

	// Drop the integer kernel's file comment, which describes the integer case.
	s = regexp.MustCompile(`(?s)\n// The 64-bit kernel.*?\n\n`).ReplaceAllString(s, "\n")

	header := fmt.Sprintf("// Code generated by gen from %s; DO NOT EDIT.\n\n", r.from)
	s = strings.Replace(s, "//go:build", header+"//go:build", 1)

	return writeFormatted(r.to, []byte(s))
}

func writeFormatted(path string, src []byte) error {
	out, err := format.Source(src)
	if err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, out) {
		return nil
	}
	return os.WriteFile(path, out, 0o644)
}
